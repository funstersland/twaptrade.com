import fs from 'node:fs';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
const cfg=JSON.parse(fs.readFileSync('.sites-runtime/postgres-test-env.json'));
if(cfg.TWAP_DB_SCHEMA!=='verification')throw Error('Only isolated verification schema is allowed');
const db=new pg.Client({connectionString:cfg.DATABASE_URL,options:'-c search_path=verification,public'});
await db.connect();
await db.query('DELETE FROM verification.auth_limits');
const origin='http://localhost:3001';let checks=0;
async function api(path,payload,cookie,expected=200){const r=await fetch(origin+path,{method:payload?'POST':'GET',headers:{origin,'content-type':'application/json',...(cookie?{cookie}:{})},...(payload?{body:JSON.stringify(payload)}:{})});const d=await r.json();assert.equal(r.status,expected,`${path} ${payload?.action}: ${JSON.stringify(d)}`);checks++;return{d,cookie:r.headers.get('set-cookie')?.split(';')[0]};}
const owner=await api('/api/auth',{action:'login',email:cfg.TWAP_ADMIN_EMAIL,password:'IsolatedOwner#2026!'});
const suffix=randomUUID().slice(0,8),email=`settings-${suffix}@example.test`,password='TestMember#2026!';
const a=await api('/api/auth',{action:'signup',name:'Account verification',email,password},null,201);
const first=await api('/api/account',{action:'init'},a.cookie);assert.equal(first.d.profile.preferences.accent,'auto');assert.equal(first.d.isNew,true);checks+=2;
const second=await api('/api/account',{action:'init'},a.cookie);assert.equal(second.d.isNew,false);checks++;
await api('/api/account',{action:'save',preferences:{theme:'system',accent:'auto',density:'compact',motion:'reduced'}},a.cookie);
const login=await api('/api/auth',{action:'login',email,password});
const restored=await api('/api/account',{action:'init'},login.cookie);
assert.notEqual(restored.d.sessionAccent,first.d.sessionAccent);assert.equal(restored.d.profile.preferences.density,'compact');checks+=2;
const oldSession=await api('/api/account',{action:'init'},a.cookie);assert.equal(oldSession.d.sessionAccent,first.d.sessionAccent);checks++;
const person=(await db.query('SELECT user_id,referral_code FROM profiles WHERE email=$1',[email])).rows[0];
await api('/api/auth',{action:'signup',name:'Referred verification',email:`referred-${suffix}@example.test`,password,referral:person.referral_code},null,201);
const referrals=await api('/api/account',{action:'init'},login.cookie);assert.equal(referrals.d.referralCount,1);checks++;
await api('/api/auth',{action:'change-password',currentPassword:'Incorrect#2026!',password:'UpdatedMember#2026!'},login.cookie,400);
await api('/api/auth',{action:'change-password',currentPassword:password,password:'UpdatedMember#2026!'},login.cookie);
await api('/api/account',{action:'init'},a.cookie,401);
await api('/api/auth',{action:'login',email,password},null,401);
const updated=await api('/api/auth',{action:'login',email,password:'UpdatedMember#2026!'});
const reset=await api('/api/admin',{action:'reset-password',id:person.user_id},owner.cookie);
const token=new URL(reset.d.resetPath,origin).searchParams.get('token');assert(token);checks++;
await api('/api/auth',{action:'reset-password',token,password:'RecoveredMember#2026!'});
await api('/api/auth',{action:'reset-password',token,password:'UnwantedReplay#2026!'},null,400);
await api('/api/account',{action:'init'},updated.cookie,401);
await api('/api/auth',{action:'login',email,password:'RecoveredMember#2026!'});
console.log(`PostgreSQL account verification: ${checks} checks passed.`);
await db.end();
